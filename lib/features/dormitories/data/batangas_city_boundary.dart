  static final LatLngBounds mapBounds = LatLngBounds.fromPoints(
    polygons.expand((polygon) => polygon).toList(growable: false),
  );

  static List<LatLng> get mapBoundsRing {
    const padding = 0.02;
    final south = mapBounds.south - padding;
    final north = mapBounds.north + padding;
    final west = mapBounds.west - padding;
    final east = mapBounds.east + padding;
    return [
      LatLng(south, west),
      LatLng(north, west),
      LatLng(north, east),
      LatLng(south, east),
      LatLng(south, west),
    ];
  }

  static bool contains(LatLng point) {
    return polygons.any((polygon) => _containsInRing(point, polygon));
  }

  static bool _containsInRing(LatLng point, List<LatLng> ring) {
    var inside = false;
    for (var current = 0, previous = ring.length - 1;
        current < ring.length;
        previous = current++) {
      final currentPoint = ring[current];
      final previousPoint = ring[previous];
      final crossesLatitude =
          (currentPoint.latitude > point.latitude) !=
          (previousPoint.latitude > point.latitude);
      if (!crossesLatitude) continue;

      final crossingLongitude =
          (previousPoint.longitude - currentPoint.longitude) *
              (point.latitude - currentPoint.latitude) /
              (previousPoint.latitude - currentPoint.latitude) +
          currentPoint.longitude;
      if (point.longitude < crossingLongitude) inside = !inside;
    }
    return inside;
  }
